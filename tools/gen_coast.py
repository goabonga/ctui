"""Generate src/map_coast.c from a coastline in JSON.

The input is a list of polylines, each a list of [longitude, latitude]
pairs in degrees (the Natural Earth 1:110m coastline, public domain,
https://www.naturalearthdata.com/, simplified to 0.01 degree). Run it once
and commit the result:

    python3 tools/gen_coast.py world_coastline.json src/map_coast.c
    make format

Coordinates are stored as int16 hundredths of a degree.
"""
import json
import sys


def block(items):
    rows = []
    for i in range(0, len(items), 12):
        rows.append("    " + ", ".join(str(v) for v in items[i:i + 12]) + ",")
    return "\n".join(rows)


def main(argv):
    if len(argv) != 3:
        sys.exit("usage: gen_coast.py coastline.json out.c")
    with open(argv[1], encoding="utf-8") as f:
        lines = json.load(f)
    lengths = []
    values = []
    for line in lines:
        if not 2 <= len(line) <= 0xFFFF:
            sys.exit("a polyline needs 2 to 65535 points")
        lengths.append(len(line))
        for lon, lat in line:
            x, y = round(lon * 100), round(lat * 100)
            if not (-18000 <= x <= 18000 and -9000 <= y <= 9000):
                sys.exit(f"coordinate out of range: {lon}, {lat}")
            values += [x, y]

    out = f"""/* SPDX-License-Identifier: MIT
 *
 * map_coast.c - the world coastline of the map component.
 *
 * GENERATED by tools/gen_coast.py, do not edit.
 *
 * Natural Earth 1:110m coastline, public domain
 * (https://www.naturalearthdata.com/), simplified to 0.01 degree: {len(lengths)}
 * polylines, {len(values) // 2} points, longitude and latitude in hundredths
 * of a degree.
 */
#include "map_coast.h"

const size_t ht_map_coast_line_count = {len(lengths)};

const uint16_t ht_map_coast_lengths[] = {{
{block(lengths)}
}};

const int16_t ht_map_coast_points[] = {{
{block(values)}
}};
"""
    with open(argv[2], "w", encoding="utf-8") as f:
        f.write(out)


main(sys.argv)
